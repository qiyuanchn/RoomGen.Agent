def catalog_path(cache_root: str, scene_id: str, profile, count: int,
                 base_seed: int) -> str:
    return os.path.join(cache_root, scene_id, profile.fingerprint(),
                        f"episodes_{count}_{base_seed}.json")


def save_catalog(catalog: EpisodeCatalog, path: str) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(catalog.to_dict(), handle, indent=2)


def load_catalog(path: str) -> EpisodeCatalog:
    with open(path, "r", encoding="utf-8") as handle:
        return EpisodeCatalog.from_dict(json.load(handle))


def load_or_generate(scene_id: str, spec, profile, nav, count: int,
                     base_seed: int, cache_root: str,
                     rebuild: bool = False) -> Tuple[EpisodeCatalog, str]:
    path = catalog_path(cache_root, scene_id, profile, count, base_seed)
    if not rebuild and os.path.isfile(path):
        try:
            catalog = load_catalog(path)
            if catalog.scene_id == scene_id and len(catalog.episodes) == count \
                    and catalog.base_seed == base_seed:
                return catalog, "cache"
        except Exception:
            pass
    catalog = generate_catalog(scene_id, spec, profile, nav, count, base_seed)
    save_catalog(catalog, path)
    return catalog, "generated"


def verify_catalog(scene_id: str, spec, profile, nav, catalog: EpisodeCatalog,
                   limit: Optional[int] = None) -> dict:
    """Replay stored action lists and compare with the recorded reference run."""
    env = PointNavEnv(scene_id, spec, profile, nav)
    checked = 0
    failures = []
    for episode in catalog.episodes:
        if limit is not None and checked >= limit:
            break
        env.reset(scene_id, episode.episode_id, episode.seed, episode=episode)
        env.rollout(episode.actions)
        result = env.evaluate()
        checked += 1
        if not result["success"]:
            failures.append({"episode_id": episode.episode_id,
                             "failure_reason": result["failure_reason"],
                             "final_distance": result["final_distance"]})
        elif abs(result["final_distance"] - episode.reference_final_distance) > 1e-6:
            failures.append({"episode_id": episode.episode_id,
                             "failure_reason": "non_reproducible_final_state",
                             "final_distance": result["final_distance"]})
    return {"checked": checked,
            "failures": failures[:50],
            "ok": not failures and checked == (len(catalog.episodes) if limit is None else checked)}
