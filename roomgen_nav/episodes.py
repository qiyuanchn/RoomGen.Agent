"""Deterministic PointNav episode generation and caching.

An episode is fully reproducible from ``(scene_id, episode_id, base_seed)``:
the seed feeds a ``random.Random`` used for room sampling, the initial state is
stored explicitly, and the reference action list is generated by replaying the
composite path through the same :class:`~roomgen_nav.env.PointNavEnv` motion
model.  That action list is an **oracle sanity check** (the reference path is
executable); it is not a policy.  Policy evaluation runs
:class:`~roomgen_nav.env.ShortestPathPolicy` closed-loop over the stored
``reference_path`` waypoints and reports its own success / SPL / collisions.

:func:`episode_record` serialises one policy rollout to the line format consumed
by ``tools/build_nav_replay.py`` (``episodes.jsonl``).

Episode mix
-----------
For a multi-storey scene about 40% of the tasks start and end on different
floors and must use a stair / ramp link.  A one-storey scene with a split-level
ramp gets a few tasks between the linked rooms.  The rest are same-floor room to
room tasks.  If a requested kind cannot be sampled (e.g. a wheeled profile
cannot use the only stair), generation falls back to reachable same-floor
tasks and records the reason in the catalog report.
"""

from __future__ import annotations

import json
import os
import random
from dataclasses import dataclass, field, asdict
from typing import Dict, List, Optional, Sequence, Tuple

from roomgen_nav import assets
from roomgen_nav.env import PointNavEnv, script_actions
from roomgen_nav.pathfinding import point_distance


@dataclass
class Episode:
    scene_id: str
    episode_id: int
    seed: int
    start_position: List[float]
    start_yaw_deg: float
    goal_position: List[float]
    start_floor: str
    goal_floor: str
    start_room: str
    goal_room: str
    shortest_distance: float
    reference_path: List[List[float]] = field(default_factory=list)
    actions: List[str] = field(default_factory=list)
    links_used: List[str] = field(default_factory=list)
    cross_floor: bool = False
    strategy: str = "same_floor"
    reference_success: bool = False
    reference_final_distance: float = 0.0
    reference_collisions: int = 0
    reference_steps: int = 0
    reference_spl: float = 0.0
    failures: List[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, data: dict) -> "Episode":
        allowed = {field.name for field in cls.__dataclass_fields__.values()}
        return cls(**{key: value for key, value in data.items() if key in allowed})


def episode_record(episode: Episode, result: dict, trajectory: Sequence[dict],
                   policy: Optional[str] = None, profile=None) -> dict:
    """One ``episodes.jsonl`` line in the ``tools/build_nav_replay.py`` contract.

    Required keys: ``scene_id, episode_id, seed, start, goal, start_floor,
    goal_floor, reference_path {points, distance}, trajectory [{position, yaw,
    action, collision}], success, spl, collisions, timeout, failure_reason``.
    Yaw unit / convention are declared explicitly so the replay tool does not
    have to guess them from the motion.
    """
    record = {
        "scene_id": episode.scene_id,
        "episode_id": int(episode.episode_id),
        "seed": int(episode.seed),
        "start": [float(value) for value in episode.start_position],
        "goal": [float(value) for value in episode.goal_position],
        "start_floor": str(episode.start_floor),
        "goal_floor": str(episode.goal_floor),
        "reference_path": {
            "points": [[float(value) for value in point]
                       for point in episode.reference_path],
            "distance": float(episode.shortest_distance),
        },
        "trajectory": [
            {
                "position": [float(value) for value in step["position"]],
                "yaw": float(step["yaw"]),
                "action": step.get("action"),
                "collision": bool(step.get("collision", False)),
                "floor_id": step.get("floor_id"),
            }
            for step in trajectory
        ],
        "success": bool(result["success"]),
        "spl": float(result["spl"]),
        "collisions": int(result["collisions"]),
        "timeout": bool(result["timeout"]),
        "failure_reason": result.get("failure_reason"),
        "policy": policy,
        "profile": getattr(profile, "name", None),
        "strategy": episode.strategy,
        "cross_floor": bool(episode.cross_floor),
        "links_used": list(episode.links_used),
        "steps": int(result.get("steps", max(0, len(trajectory) - 1))),
        "path_length": float(result.get("path_length", 0.0)),
        "final_distance": float(result.get("final_distance", 0.0)),
        "shortest_distance": float(episode.shortest_distance),
        "yaw_unit": "degrees",
        "yaw_convention": "manifest",
    }
    if result.get("oracle") is not None:
        record["oracle"] = result["oracle"]
    return record


def write_episode_jsonl(handle, record: dict) -> None:
    """Append one compact JSON line (the caller owns line ordering)."""
    handle.write(json.dumps(record, ensure_ascii=False, separators=(",", ":")) + "\n")


@dataclass
class EpisodeCatalog:
    scene_id: str
    profile: str
    base_seed: int
    episodes: List[Episode]
    report: dict = field(default_factory=dict)

    def __len__(self) -> int:
        return len(self.episodes)

    def get(self, episode_id: int, seed: Optional[int] = None) -> Episode:
        for episode in self.episodes:
            if episode.episode_id == int(episode_id):
                if seed is not None and episode.seed != int(seed):
                    # Explicit seeds are a reproducibility promise: regenerate
                    # rather than returning an episode from another stream.
                    raise KeyError(
                        f"episode {episode_id} was generated with seed {episode.seed}, "
                        f"not {seed}")
                return episode
        raise KeyError(f"episode {episode_id} not in catalog")

    def to_dict(self) -> dict:
        return {
            "scene_id": self.scene_id,
            "profile": self.profile,
            "base_seed": self.base_seed,
            "count": len(self.episodes),
            "report": self.report,
            "episodes": [episode.to_dict() for episode in self.episodes],
        }

    @classmethod
    def from_dict(cls, data: dict) -> "EpisodeCatalog":
        return cls(
            scene_id=str(data["scene_id"]),
            profile=str(data.get("profile", "")),
            base_seed=int(data.get("base_seed", 0)),
            episodes=[Episode.from_dict(item) for item in data.get("episodes", [])],
            report=dict(data.get("report", {})),
        )


