def _rooms_by_floor(spec) -> Dict[str, List[str]]:
    out: Dict[str, List[str]] = {}
    for room in spec.rooms:
        floor_id = assets.floor_id_of_room(spec, room.id)
        out.setdefault(floor_id, []).append(room.id)
    return out


def _strategy_sequence(count: int, spec, profile, nav) -> List[str]:
    cross = [link for link in nav.valid_links if link.is_cross_floor]
    linked = [link for link in nav.valid_links if not link.is_cross_floor]
    if cross:
        cross_count = min(count, max(1, int(round(count * 0.4))))
    else:
        cross_count = 0
    linked_count = min(count - cross_count, max(1, int(round(count * 0.2)))) if linked else 0
    if linked and count <= 5:  # smoke runs still touch a ramp / split level
        linked_count = min(count - cross_count, 1)
    return (["cross_floor"] * cross_count + ["linked"] * linked_count
            + ["same_floor"] * (count - cross_count - linked_count))


def _pick_rooms(rng: random.Random, spec, strategy: str, nav, profile):
    rooms = _rooms_by_floor(spec)
    if strategy == "cross_floor":
        candidates = [link for link in nav.valid_links if link.is_cross_floor]
        rng.shuffle(candidates)
        for link in candidates:
            start_rooms = rooms.get(link.from_floor, [])
            goal_rooms = rooms.get(link.to_floor, [])
            if start_rooms and goal_rooms:
                return (rng.choice(start_rooms), rng.choice(goal_rooms),
                        link.from_floor, link.to_floor, link)
        return None
    if strategy == "linked":
        candidates = [link for link in nav.valid_links if not link.is_cross_floor]
        rng.shuffle(candidates)
        for link in candidates:
            return link.from_room, link.to_room, link.from_floor, link.to_floor, link
        return None
    floor_ids = [floor_id for floor_id, items in rooms.items() if len(items) >= 2]
    if not floor_ids:
        floor_ids = [floor_id for floor_id, items in rooms.items() if items]
    if not floor_ids:
        return None
    floor_id = rng.choice(floor_ids)
    items = rooms[floor_id]
    start = rng.choice(items)
    goal = rng.choice([room for room in items if room != start] or items)
    return start, goal, floor_id, floor_id, None


def _sample_episode(index: int, seed: int, scene_id: str, spec, profile, nav,
                    strategy: str, env: PointNavEnv,
                    min_distance: float) -> Optional[Episode]:
    rng = random.Random(seed)
    for _attempt in range(120):
        picked = _pick_rooms(rng, spec, strategy, nav, profile)
        if picked is None:
            return None
        start_room, goal_room, start_floor, goal_floor, link = picked
        sampled = nav.sample_start_goal(start_room, goal_room, rng,
                                        min_distance=min_distance)
        if sampled is None:
            continue
        start_floor, start, goal_floor, goal, path = sampled
        if strategy == "cross_floor":
            if start_floor == goal_floor or not path.links_used:
                continue
            if not any(link_id.startswith("stair_") or link_id.startswith("ramp_")
                       for link_id in path.links_used):
                continue
        if strategy == "linked" and link is not None:
            if start_room not in (link.from_room, link.to_room):
                continue
        if point_distance(start, goal) < min_distance:
            continue
        start_yaw = 0.0
        if len(path.points) >= 2:
            from roomgen_nav.pathfinding import heading_deg
            start_yaw = heading_deg(path.points[0], path.points[1])

        episode = Episode(
            scene_id=scene_id,
            episode_id=index,
            seed=seed,
            start_position=[float(v) for v in start],
            start_yaw_deg=float(start_yaw),
            goal_position=[float(v) for v in goal],
            start_floor=start_floor,
            goal_floor=goal_floor,
            start_room=start_room,
            goal_room=goal_room,
            shortest_distance=float(path.distance),
            reference_path=[[float(v) for v in p] for p in path.points],
            links_used=list(path.links_used),
            cross_floor=start_floor != goal_floor,
            strategy=strategy,
        )
        env.reset(scene_id, episode.episode_id, episode.seed, episode=episode)
        actions = script_actions(env, path)
        result = env.evaluate()
        episode.actions = list(actions)
        episode.reference_success = bool(result["success"])
        episode.reference_final_distance = float(result["final_distance"])
        episode.reference_collisions = int(result["collisions"])
        episode.reference_steps = int(result["steps"])
        episode.reference_spl = float(result["spl"])
        if episode.reference_success:
            return episode
    return None


def _preflight_reachability(nav, spec, base_seed: int) -> dict:
    """Cheap room-level connectivity probe before sampling thousands of points.

    A wheeled bake can leave every room on its own island (doors narrower than
    the agent).  Sampling room pairs blindly then spends minutes proving that no
    path exists.  Up to three points per room (one per NavMesh island) and a few
    Dijkstra runs answer the same question in a fraction of a second.
    """
    rng = random.Random(assets.stable_seed("preflight", nav.entry.scene_id, base_seed))
    samples = {}
    for room in spec.rooms:
        floor_id = assets.floor_id_of_room(spec, room.id)
        floor_nav = nav.floor(floor_id)
        by_island = {}
        for _ in range(12):
            point = nav.sample_room_point(room.id, rng)
            if point is None:
                continue
            island = floor_nav.pathfinder.get_island(point)
            by_island.setdefault(island, point)
            if len(by_island) >= 3:
                break
        if by_island:
            samples[room.id] = [(floor_id, point) for point in by_island.values()]
    out = {"same_floor": False, "cross_floor": False, "linked": False,
           "rooms_with_point": sorted(samples)}
    if len(samples) < 2:
        return out
    link_pairs = {tuple(sorted((link.from_room, link.to_room)))
                  for link in nav.valid_links if not link.is_cross_floor}
    room_ids = sorted(samples)
    for i, room_a in enumerate(room_ids):
        for room_b in room_ids[i + 1:]:
            reached = False
            for floor_a, point_a in samples[room_a]:
                for floor_b, point_b in samples[room_b]:
                    path = nav.find_path(floor_a, point_a, floor_b, point_b)
                    if path is None or path.distance < 1.0:
                        continue
                    if floor_a == floor_b:
                        out["same_floor"] = True
                        if tuple(sorted((room_a, room_b))) in link_pairs:
                            out["linked"] = True
                    elif path.links_used:
                        out["cross_floor"] = True
                    reached = True
                    break
                if reached:
                    break
    return out


def generate_catalog(scene_id: str, spec, profile, nav, count: int = 50,
                     base_seed: int = 20261018, max_empty_rounds: int = 30) -> EpisodeCatalog:
    """Generate ``count`` executable episodes for one scene / profile."""
    env = PointNavEnv(scene_id, spec, profile, nav)
    preflight = _preflight_reachability(nav, spec, base_seed)
    strategies = _strategy_sequence(count, spec, profile, nav)
    if not preflight["same_floor"] and not preflight["cross_floor"]:
        return EpisodeCatalog(scene_id, profile.name, base_seed, [], {
            "requested": count, "generated": 0, "base_seed": base_seed,
            "cross_floor": 0, "same_floor": 0,
            "requested_mix": {name: strategies.count(name)
                              for name in ("cross_floor", "linked", "same_floor")},
            "valid_links": [link.link_id for link in nav.valid_links],
            "invalid_links": [{"link_id": link.link_id, "reason": link.reason}
                              for link in nav.links if not link.valid],
            "preflight": preflight,
            "failures": ["no reachable room pair for this profile"],
            "all_reference_success": False,
        })
    episodes: List[Episode] = []
    failures: List[str] = []
    attempts: Dict[str, int] = {"cross_floor": 0, "linked": 0, "same_floor": 0}
    empty_rounds = 0
    index = 0
    while len(episodes) < count and index < count * 8 and empty_rounds < max_empty_rounds:
        strategy = strategies[min(index, len(strategies) - 1)]
        if strategy == "cross_floor" and not preflight["cross_floor"]:
            failures.append("no cross-floor room pair for this profile")
            index += 1
            continue
        if strategy == "linked" and not preflight["linked"]:
            failures.append("no reachable linked room pair for this profile")
            index += 1
            continue
        if strategy == "same_floor" and not preflight["same_floor"]:
            failures.append("no reachable same-floor room pair for this profile")
            index += 1
            continue
        if empty_rounds:
            # A failed strategy must not replay the same 120 samples forever;
            # the salt only changes retry streams, so the first-attempt seeds
            # (and the full-run episode cache) stay stable.
            seed = assets.stable_seed(scene_id, "episode", len(episodes),
                                      empty_rounds, base_seed)
        else:
            seed = assets.stable_seed(scene_id, "episode", len(episodes), base_seed)
        episode = _sample_episode(len(episodes), seed, scene_id, spec, profile, nav,
                                  strategy, env, min_distance=1.5)
        if episode is None:
            failures.append(f"could not sample strategy '{strategy}'")
            empty_rounds += 1
            index += 1
            continue
        empty_rounds = 0
        attempts[strategy] = attempts.get(strategy, 0) + 1
        episodes.append(episode)
        index += 1
    cross_count = sum(1 for episode in episodes if episode.cross_floor)
    report = {
        "requested": count,
        "generated": len(episodes),
        "base_seed": base_seed,
        "cross_floor": cross_count,
        "same_floor": len(episodes) - cross_count,
        "requested_mix": {name: strategies.count(name)
                          for name in ("cross_floor", "linked", "same_floor")},
        "valid_links": [link.link_id for link in nav.valid_links],
        "invalid_links": [{"link_id": link.link_id, "reason": link.reason}
                          for link in nav.links if not link.valid],
        "preflight": preflight,
        "failures": failures[:50],
        "all_reference_success": all(episode.reference_success for episode in episodes),
    }
    return EpisodeCatalog(scene_id, profile.name, base_seed, episodes, report)


